  const STORAGE_KEY = "collie.lang";
  const VALID_PREFS = new Set(["auto", "zh", "en"]);

  function normalizePref(v) {
    const s = String(v ?? "").trim().toLowerCase();
    return VALID_PREFS.has(s) ? s : "auto";
  }

  function detectSystemLang(navLang) {
    let raw = navLang;
    if (raw === undefined) {
      try {
        raw = navigator.language || (Array.isArray(navigator.languages) ? navigator.languages[0] : "") || "";
      } catch {
        raw = "";
      }
    }
    return /^zh(?:[-_]|$)/i.test(String(raw || "").trim()) ? "zh" : "en";
  }

  function readPref() {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (raw == null || raw === "") return "auto";
      try {
        return normalizePref(JSON.parse(raw));
      } catch {
        return normalizePref(raw);
      }
    } catch {
      return "auto";
    }
  }

  function writePref(pref) {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(normalizePref(pref)));
    } catch {}
  }

  function resolveLang(pref = readPref(), navLang) {
    const p = normalizePref(pref);
    if (p === "zh" || p === "en") return p;
    return detectSystemLang(navLang);
  }

  function htmlLang(lang) {
    return lang === "en" ? "en" : "zh-CN";
  }

  function localeFor(lang) {
    return lang === "en" ? "en-US" : "zh-CN";
  }

