    if (!vars || typeof tpl !== "string") return String(tpl ?? "");
    return tpl.replace(/\{([a-zA-Z0-9_]+)\}/g, (m, k) => (
      Object.prototype.hasOwnProperty.call(vars, k) && vars[k] !== undefined && vars[k] !== null
        ? String(vars[k])
        : m
    ));
