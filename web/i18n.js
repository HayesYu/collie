  function setLeadingText(el, text) {
    if (!el) return;
    const first = el.firstChild;
    if (first && first.nodeType === 3) {
      const want = text + " ";
      if (first.nodeValue !== want) first.nodeValue = want;
    } else if (typeof document !== "undefined" && document.createTextNode) {
      el.insertBefore(document.createTextNode(text + " "), first || null);
    }
  }

  function syncHtmlAttrs() {
    if (typeof document === "undefined" || !document.documentElement) return;
    document.documentElement.lang = htmlLang(curLang);
    document.documentElement.dataset.lang = curLang;
    document.documentElement.dataset.langPref = curPref;
  }

  function applyDOM(root) {
    const doc = root || (typeof document !== "undefined" ? document : null);
    if (!doc || typeof doc.querySelectorAll !== "function") return;
    syncHtmlAttrs();
    doc.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.getAttribute("data-i18n");
      if (k) el.textContent = t(k);
    });
    doc.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const k = el.getAttribute("data-i18n-html");
      if (k) el.innerHTML = t(k);
    });
    doc.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const k = el.getAttribute("data-i18n-placeholder");
      if (k) el.setAttribute("placeholder", t(k));
    });
    doc.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const k = el.getAttribute("data-i18n-title");
      if (k) el.title = t(k);
    });
    doc.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const k = el.getAttribute("data-i18n-aria");
      if (k) el.setAttribute("aria-label", t(k));
    });
    doc.querySelectorAll("[data-i18n-sub]").forEach((el) => {
      const k = el.getAttribute("data-i18n-sub");
      if (k) el.dataset.sub = t(k);
    });
    doc.querySelectorAll("[data-i18n-pick-title]").forEach((el) => {
      const k = el.getAttribute("data-i18n-pick-title");
      if (k) el.dataset.title = t(k);
    });
    doc.querySelectorAll("[data-i18n-lead]").forEach((el) => {
      const k = el.getAttribute("data-i18n-lead");
      if (!k) return;
      const target = el.tagName === "SUMMARY" ? (el.querySelector("h2") || el) : el;
      setLeadingText(target, t(k));
    });
    // Preserve exact `<span>小本本</span>` markup in web/index.html for static contract tests
    const notesBtnSpan = doc.querySelector?.("#open-notes-btn > span:first-child");
    if (notesBtnSpan) notesBtnSpan.textContent = t("collie.notes");
    // Sync document title for default/demo shells
    if (doc === document && typeof document.title === "string") {
      if (window.__collieDemo) document.title = t("demo.title");
      else if (!document.title || document.title === "Collie") document.title = t("app.title");
    }
  }

  function notifyListeners() {
    const detail = { pref: curPref, lang: curLang };
    for (const fn of listeners) {
      try { fn(detail); } catch {}
    }
    try {
      if (typeof window !== "undefined" && typeof window.dispatchEvent === "function" && typeof CustomEvent === "function") {
        window.dispatchEvent(new CustomEvent("collie:lang", { detail }));
      }
    } catch {}
  }

  function setLang(pref, opts = {}) {
    const { persist = true, notify = true, navLang } = opts;
    const nextPref = normalizePref(pref);
    const nextLang = resolveLang(nextPref, navLang);
    const changed = nextPref !== curPref || nextLang !== curLang;
    curPref = nextPref;
    curLang = nextLang;
    if (persist) writePref(curPref);
    applyDOM();
    if (notify && changed) notifyListeners();
    return curLang;
  }

  function onChange(fn) {
    if (typeof fn !== "function") return () => {};
    listeners.add(fn);
    return () => listeners.delete(fn);
  }

